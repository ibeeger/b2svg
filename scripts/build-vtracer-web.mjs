// Generates a browser-ready ESM build of @visioncortex/vtracer.
//
// The published package is built with `wasm-pack --target nodejs`, so its glue
// uses CJS `exports` and loads the .wasm with `require('fs')`. Everything else
// in that file is standard JS + WebAssembly + TextEncoder/TextDecoder, which
// browsers already have. This script rewrites only those two node-isms and
// copies the .wasm alongside, so `npm update` re-generates cleanly instead of
// silently reverting a hand-patched vendor file.

import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkgDir = dirname(require.resolve('@visioncortex/vtracer/pkg/vtracer_wasm.js'));
const outDir = join(root, 'src', 'vendor');

const NODE_LOADER = /const wasmPath = [\s\S]*?wasm\.__wbindgen_start\(\);\s*$/;

const BROWSER_LOADER = `
// --- browser loader (generated by scripts/build-vtracer-web.mjs) ---
let wasm;
let initPromise;

/**
 * Instantiate the wasm module. Safe to call repeatedly; the work happens once.
 * @param {string | URL | Response | ArrayBuffer} source .wasm URL or bytes
 */
export function initVTracer(source) {
  if (!initPromise) {
    initPromise = (async () => {
      const imports = __wbg_get_imports();
      let instance;
      if (source instanceof ArrayBuffer || ArrayBuffer.isView(source)) {
        ({ instance } = await WebAssembly.instantiate(source, imports));
      } else {
        const res = source instanceof Response ? source : await fetch(source);
        if (!res.ok) throw new Error(\`failed to fetch vtracer wasm: \${res.status}\`);
        // Fall back to ArrayBuffer when the server sends the wrong MIME type.
        if (res.headers.get('content-type')?.includes('application/wasm')) {
          ({ instance } = await WebAssembly.instantiateStreaming(res, imports));
        } else {
          ({ instance } = await WebAssembly.instantiate(await res.arrayBuffer(), imports));
        }
      }
      wasm = instance.exports;
      wasm.__wbindgen_start();
    })().catch((err) => {
      initPromise = undefined; // let the caller retry
      throw err;
    });
  }
  return initPromise;
}

export { vectorize_bytes, vectorize_rgba };
`;

const src = await readFile(join(pkgDir, 'vtracer_wasm.js'), 'utf8');

if (!NODE_LOADER.test(src)) {
  throw new Error(
    'vtracer glue no longer ends with the expected node loader — ' +
      'inspect node_modules/@visioncortex/vtracer/pkg/vtracer_wasm.js and update this script.',
  );
}

const out = src
  .replace(/^exports\.(\w+) = \1;$/gm, '')
  .replace(NODE_LOADER, BROWSER_LOADER);

if (/\brequire\s*\(|__dirname/.test(out)) {
  throw new Error('generated glue still references node built-ins');
}

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'vtracer_wasm.js'), out);
await copyFile(join(pkgDir, 'vtracer_wasm_bg.wasm'), join(outDir, 'vtracer_wasm_bg.wasm'));
await copyFile(join(pkgDir, 'vtracer_wasm.d.ts'), join(outDir, 'vtracer_wasm.d.ts'));

console.log(`vtracer browser glue written to ${outDir}`);
